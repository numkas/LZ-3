#Для всех выселений нам надо число п, можно использовать бд либо самому её задать
P = 3.14 
#Вводим радиус 
print("Введите радиус ")
#Команда благодаря которой мы сможешь ввести нашезначение(Float - дробные числа)
r = float(input())
#Так как нам нужны вычисление и в сантиметрах и в метрах, переводим
rm = r/100
#Теперь просим компуктер посчитсть нам площадь кргуга и его длину
print(f"Длина окружности {2*P*r} см или {2*P*rm} м")
#Аналогично пишем для всех знаечний. Площадб круга
print(f"Площадь круга {P*r**2} см или {P*rm**2} м")
#Длина стораны правильного треугольника вписанного в окружность
print(f"Длина стораны правилного треугольника вписанного в окружность {r*(3**0.5)} см или {rm*(3**0.5)} м")
#Ддина стороны квадрата вписанного в окружность
print(f"Длина стораны квадрата вписанного в окружность {r*(2**0.5)} см или {rm*(2**0.5)} м")
#Ддина описанного правильного треугольника вокруг окружности
print(f"Длина стораны правилного треугольника описанного вокруг окружность {2*r*3**0.5} см или {(2*rm*3**0.5)} м")
#Ддина стороны квадрата описанного вокруг окружность
print(f"Длина стораны квадрата описанного около окружность {2*r} см или {2*rm} м")
#Ддина стороны восьмиугольника описанного вокруг окружность
print(f"Длина стораны восьмиугольника описанного около окружность {2*r*(2**0.5 - 1)} см или {2*rm*(2**0.5 - 1)} м")
